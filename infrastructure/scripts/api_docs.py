"""Regenerates the endpoint reference of docs/API.md and docs/openapi.json from the application itself, so the
documentation can never drift from the code:

    python -m infrastructure.scripts.api_docs

The part of docs/API.md above the «Endpoint reference» heading is written by hand and kept as it is.
"""
import json
import os
import re
import secrets
from pathlib import Path

os.environ.setdefault("DATABASE_URL", "sqlite://")
os.environ.setdefault("JWT_SECRET", secrets.token_hex(32))
os.environ.setdefault("BOT_SERVICE_KEY", secrets.token_hex(32))

from backend.main import app  # noqa: E402
from backend.services.team import RULES  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
MARKER = "## Endpoint reference"
GROUPS = [("/api/auth", "Sign-in"), ("/api/admin", "Dashboard API"), ("/internal", "Bot API (service key)"), ("/health", "Health")]


def permission(method: str, path: str) -> str:
    """The permission RULES require for a dashboard route ("signed in" when any staff member may call it)."""
    path = re.sub(r"{(\w*_)?id}", "1", path)  # ids are numbers
    for sample in ("1", "en", "general", "tickets", "start", "x"):  # other parameters: codes, enumerated names
        concrete = re.sub(r"{[^}]+}", sample, path)
        for methods, pattern, wanted in RULES:
            if method in methods and pattern.match(concrete):
                if wanted is None:
                    return "signed in"
                return " or ".join(f"`{p}`" for p in (wanted if isinstance(wanted, tuple) else (wanted,)))
    return "**no rule — refused**"


def summary(operation: dict) -> str:
    text = (operation.get("description") or "").strip().split("\n\n")[0]
    return " ".join(text.split()) or operation.get("summary", "")


def reference(schema: dict) -> str:
    lines = [MARKER, "", "Generated by `python -m infrastructure.scripts.api_docs` — do not edit by hand.", ""]
    operations = [(path, method.upper(), op) for path, item in schema["paths"].items() for method, op in item.items()]
    for prefix, title in GROUPS:
        group = sorted((o for o in operations if o[0].startswith(prefix)), key=lambda o: (o[0], o[1]))
        if not group:
            continue
        dashboard = prefix == "/api/admin"
        lines += [f"### {title}", "", "| Method | Path | Permission | What it does |" if dashboard else "| Method | Path | What it does |",
                  "|---|---|---|---|" if dashboard else "|---|---|---|"]
        for path, method, op in group:
            cells = [method, f"`{path}`"] + ([permission(method, path)] if dashboard else []) + [summary(op).replace("|", "\\|")]
            lines.append("| " + " | ".join(cells) + " |")
        lines.append("")
    return "\n".join(lines)


def main() -> None:
    schema = app.openapi()
    api_md = ROOT / "docs" / "API.md"
    head = api_md.read_text(encoding="utf-8").split(MARKER)[0] if api_md.exists() else "# API\n\n"
    api_md.write_text(head + reference(schema), encoding="utf-8")
    (ROOT / "docs" / "openapi.json").write_text(json.dumps(schema, ensure_ascii=False, indent=1), encoding="utf-8")
    print("docs/API.md and docs/openapi.json updated")


if __name__ == "__main__":
    main()
